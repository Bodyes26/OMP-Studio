export type AutomationI18nKey = keyof typeof DICTIONARY['it'];

export function t(key: AutomationI18nKey, params?: Record<string, string | number>): string {
	const locale = getLocale();
	const dict = DICTIONARY[locale] || DICTIONARY.it;
	let val = dict[key] || DICTIONARY.it[key] || String(key);
	if (params) {
		for (const [k, v] of Object.entries(params)) {
			val = val.replaceAll(`{${k}}`, String(v));
		}
	}
	return val;
}

export function formatDateTime(ms: number, locale = getLocale()): string {
	if (!ms) return '—';
	try {
		return new Intl.DateTimeFormat(locale === 'it' ? 'it-IT' : 'en-US', {
			dateStyle: 'medium',
			timeStyle: 'short'
		}).format(new Date(ms));
	} catch {
		return new Date(ms).toLocaleString();
	}
}

export function formatDuration(minutes: number, locale = getLocale()): string {
	if (minutes <= 0) return '0 min';
	if (minutes < 60) return `${minutes} min`;
	const hours = Math.floor(minutes / 60);
	const rest = minutes % 60;
	if (rest === 0) return `${hours} ${locale === 'it' ? 'ore' : 'hours'}`;
	return `${hours}h ${rest}m`;
}
